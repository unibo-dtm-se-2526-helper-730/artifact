package it.helper730;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.context.annotation.Import;
import org.springframework.test.web.servlet.MockMvc;

/**
 * OpenApiSpecIT.
 *
 * The OpenAPI document generated by springdoc must match docs/openapi.json, the
 * versioned copy of the Web API specification. A change to the API that is not
 * reflected in the committed file fails the build.
 *
 * Regenerate the file with: ./mvnw verify -Dopenapi.update=true
 */
@SpringBootTest
@AutoConfigureMockMvc
@Import(TestcontainersConfiguration.class)
class OpenApiSpecIT {

    private static final Path SPEC = Path.of(System.getProperty("openapi.file", "../docs/openapi.json"));

    @Autowired
    private MockMvc mvc;

    @Test
    void committedSpecMatchesTheApi() throws Exception {
        String generated = normalize(mvc.perform(get("/v3/api-docs"))
                .andExpect(status().isOk())
                .andReturn()
                .getResponse()
                .getContentAsString(UTF_8));

        if (Boolean.getBoolean("openapi.update")) {
            Files.createDirectories(SPEC.toAbsolutePath().getParent());
            Files.writeString(SPEC, generated, UTF_8);
            return;
        }

        assertThat(SPEC)
                .as("%s is missing: run ./mvnw verify -Dopenapi.update=true", SPEC)
                .exists();
        assertThat(generated)
                .as("The API changed: run ./mvnw verify -Dopenapi.update=true and commit %s", SPEC)
                .isEqualTo(normalize(Files.readString(SPEC, UTF_8)));
    }

    private static String normalize(String json) {
        return json.replace("\r\n", "\n").strip() + "\n";
    }
}
